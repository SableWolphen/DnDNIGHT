import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({headless:true,...(process.env.BROWSER_CHANNEL ? {channel:process.env.BROWSER_CHANNEL} : {})});
await mkdir('browser-artifacts', {recursive:true});
const page = await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[]; page.on('pageerror',e=>errors.push(e.message));
await page.goto(process.env.BASE_URL || 'http://localhost:3000');
await page.getByRole('button',{name:'Edit character',exact:true}).click();
await page.getByLabel('Character name').fill('Mira Ashford');
await page.getByLabel('Class',{exact:true}).fill('Ranger');
await page.getByLabel('Level',{exact:true}).fill('3');
await page.getByRole('button',{name:'Save character',exact:true}).click();
await page.getByLabel('Strength score').fill('16');
await page.getByLabel('Current HP',{exact:true}).fill('9');
await page.getByLabel('Adventure notes').fill('Meet the party at the old watchtower.');
await page.getByLabel('Stealth',{exact:false}).check();
await page.getByRole('button',{name:'Save sheet',exact:true}).click();
await page.reload();
assert.equal(await page.getByLabel('Strength score').inputValue(),'16');
assert.equal(await page.getByLabel('Adventure notes').inputValue(),'Meet the party at the old watchtower.');
await page.screenshot({path:'browser-artifacts/character-sheets-desktop.png',fullPage:true});
await page.getByRole('link',{name:'The marketplace',exact:true}).click();
await page.getByRole('article').filter({has:page.getByRole('heading',{name:'Dagger',exact:true})}).getByRole('button',{name:'Buy',exact:true}).click();
await page.getByLabel('Quantity',{exact:true}).fill('3');
assert.equal(await page.locator('#trade-total').textContent(),'6 gp');
await page.getByRole('button',{name:'Confirm purchase'}).click();
assert.match(await page.locator('.page-heading .wallet').textContent(),/94 gp/);
await page.getByRole('button',{name:'Sell from inventory'}).click();
await page.getByRole('button',{name:'Sell',exact:true}).click();
await page.getByLabel('Quantity',{exact:true}).fill('2');
await page.getByRole('button',{name:'Confirm sale'}).click();
assert.match(await page.locator('.page-heading .wallet').textContent(),/96 gp/);
await page.getByRole('link',{name:'Character sheets',exact:true}).click();
await page.getByRole('button',{name:'Edit Dagger'}).click();
await page.getByLabel('Equipped',{exact:true}).check();
await page.getByRole('button',{name:'Save changes',exact:true}).click();
await page.getByRole('link',{name:'The marketplace',exact:true}).click();
assert.equal(await page.getByRole('button',{name:'Equipped',exact:true}).isDisabled(),true);
await page.getByRole('button',{name:'Buy items',exact:true}).click();
await page.screenshot({path:'browser-artifacts/marketplace-desktop.png',fullPage:true});
await page.getByRole('searchbox',{name:'Search items'}).fill('rope');
assert.equal(await page.getByRole('article').count(),1);
await page.getByRole('searchbox',{name:'Search items'}).fill('no such item');
assert.match(await page.locator('#products').textContent(),/No items/);
await page.getByRole('searchbox',{name:'Search items'}).fill('');
await page.getByRole('button',{name:'Create character',exact:false}).click();
await page.getByLabel('Character name').fill('Rowan');
await page.getByRole('button',{name:'Create character',exact:true}).last().click();
await page.getByRole('link',{name:'Character sheets',exact:true}).click();
assert.equal(await page.locator('.inventory-row').count(),0);
assert.equal(await page.getByLabel('Gold',{exact:true}).inputValue(),'100');
await page.getByRole('button',{name:'Mira Ashford',exact:false}).click();
assert.equal(await page.getByLabel('Gold',{exact:true}).inputValue(),'96');
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'browser-artifacts/character-sheets-mobile.png',fullPage:true});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
await page.getByRole('link',{name:'The marketplace',exact:true}).click();
await page.screenshot({path:'browser-artifacts/marketplace-mobile.png',fullPage:true});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
// Export the saved campaign, then prove it restores a changed party.
const downloadEvent=page.waitForEvent('download');
await page.getByRole('button',{name:'Export backup'}).click();
const download=await downloadEvent;
const backupPath=await download.path();
const savedCampaign=await page.evaluate(()=>localStorage.getItem('dndnight.campaign.v1'));
await page.getByRole('link',{name:'Character sheets',exact:true}).click();
await page.getByLabel('Current HP',{exact:true}).fill('999');
await page.getByRole('button',{name:'Save sheet',exact:true}).click();
assert.match(await page.locator('#notice').textContent(),/maximum HP/);
assert.equal(await page.evaluate(()=>localStorage.getItem('dndnight.campaign.v1')),savedCampaign);
page.once('dialog',d=>d.accept());
await page.getByRole('button',{name:'Create character',exact:false}).click();
await page.getByLabel('Character name').fill('Temporary adventurer');
await page.getByRole('button',{name:'Create character',exact:true}).last().click();
page.once('dialog',d=>d.accept());
await page.locator('#import').setInputFiles(backupPath);
await page.getByRole('button',{name:'Mira Ashford',exact:false}).waitFor();
assert.equal(await page.locator('.party-card').count(),2);
assert.equal(await page.evaluate(()=>localStorage.getItem('dndnight.campaign.v1')),savedCampaign);
// Bad persisted data is preserved and can be recovered with a valid backup.
await page.evaluate(()=>localStorage.setItem('dndnight.campaign.v1','broken data'));
await page.reload();
await page.getByRole('heading',{name:'Let’s recover your campaign'}).waitFor();
assert.equal(await page.evaluate(()=>localStorage.getItem('dndnight.campaign.v1')),'broken data');
page.once('dialog',d=>d.accept());
await page.locator('#import').setInputFiles(backupPath);
await page.getByRole('button',{name:'Mira Ashford',exact:false}).waitFor();
assert.equal(await page.evaluate(()=>localStorage.getItem('dndnight.campaign.v1')),savedCampaign);
assert.deepEqual(errors,[]);
await browser.close();
console.log('PASS: character edits, persistence, buying, selling, equipped-item protection, search, party isolation, mobile overflow, HP validation, backup export/import, corrupted-save recovery, and no browser errors.');
